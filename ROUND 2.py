#Импорт библиотек
import math

#Ввод координат в виде переменных
x1, y1 = map(float, input("Введите координаты первой точки(x y): ").split())
x2, y2 = map(float, input("Введите координаты второй точки(x y): ").split())

#Расчет евклидова значения
evklid_znac = math.sqrt((x1 - x2) ** 2 + (y1 - y2) ** 2)

#Вывод евклидова значения на экран
print(f"Расстояние между двумя координатами: {evklid_znac:.2f}см")
